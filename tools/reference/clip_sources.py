"""Write CLIP_SOURCES.md: every library clip -> description + source link at its timestamp.

Registry clips (id == clip name) come from data/animation/basketball_references.json (source url, t0).
Gap clips (<action>_<videoid>_<t>) come from sources/gaps/<action>__<videoid>.info.json (yt-dlp metadata).
usage: python clip_sources.py <repo> <out.md>
"""
import glob, json, os, re, sys
repo, out = sys.argv[1], sys.argv[2]
LIB = "E:/motion-reference/basketball"
reg = json.load(open(os.path.join(repo, "data/animation/basketball_references.json"), encoding="utf-8"))
segs = {s["id"]: s for s in reg["segments"]}; srcs = reg["sources"]

def at(url, t):
    t = int(t)
    if "youtube.com/watch" in url or "youtu.be/" in url:
        return f"{url}{'&' if '?' in url else '?'}t={t}s"
    return url

def mmss(t):
    t = int(t); return f"{t // 60}:{t % 60:02d}"

rows = {}
for f in sorted(glob.glob(LIB + "/clips/*/*.mp4")):
    if "_pose" in f: continue
    act = os.path.basename(os.path.dirname(f)); cid = os.path.basename(f)[:-4]
    if cid in segs:
        s = segs[cid]; src = srcs[s["source"]]; t0 = s["t0"]
        skip = set(act.split("_")) | {"ft", "reb", "def", "off", "live", "jump", "shot"}
        who = " ".join(w.capitalize() if w.islower() else w for w in cid.split("_") if not w.isdigit() and w.lower() not in skip)
        note = (s.get("notes") or "").split(". ")[0].strip().rstrip(".")
        if note.startswith("One-second"): note = ""
        desc = f"{who} {act.replace('_', ' ')}".strip() + (f": {note}" if note else "")
        title = src.get("title", s["source"]); url = src["url"]
    else:
        m = re.match(r"(.+)_([A-Za-z0-9_-]{11})_(\d+)$", cid); vid, t0 = m.group(2), int(m.group(3))
        info = json.load(open(f"{LIB}/sources/gaps/{act}__{vid}.info.json", encoding="utf-8"))
        title = info.get("title", vid); url = info.get("webpage_url", f"https://www.youtube.com/watch?v={vid}")
        desc = f"{act.replace('_', ' ').capitalize()} (compilation clip)"
    rows.setdefault(act, []).append((cid, desc, title, at(url, t0), mmss(t0)))

md = ["# Clip sources: basketball real-clip library", "",
      "Every clip in the local library (`E:/motion-reference/basketball/clips/<action>/<clip>.mp4`, not committed), "
      "with what it shows and a link to the original video at the clip's start time. "
      "Pose files are named `<clip>_pose.json`. Generated by `tools/reference/clip_sources.py`.", ""]
for act in sorted(rows):
    md += [f"## {act} ({len(rows[act])})", "", "| clip | description | source (opens at start) |", "|---|---|---|"]
    for cid, desc, title, url, t in rows[act]:
        md.append(f"| `{cid}` | {desc.replace('|', '/')} | [{title.replace('|', '/')} @ {t}]({url}) |")
    md.append("")
open(out, "w", encoding="utf-8").write("\n".join(md))
json.dump({c[0]: {"action": a, "description": c[1], "title": c[2], "url": c[3]} for a, r in rows.items() for c in r},
          open(out[:-3] + ".json", "w", encoding="utf-8"), indent=1)
print(sum(len(r) for r in rows.values()), "clips")
